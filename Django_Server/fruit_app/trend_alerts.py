"""Rule-based trend alerts over the detection dataset (ADR-0022).

Three layers, all generated by Django:

1. Detection: after any graded result is saved, the six observation
   categories and the processing-fruit share run through the same generic
   rules on every graded fruit in the detection partition: share over a
   threshold in the latest
   window, a rise against the previous window of the same length, and a
   same-day spike against the window before today.
2. Severity: every category has its own threshold, rise and advice
   direction; one global minimum sample size guards every comparison. Adding
   a model class only adds a ``DEFAULT_CATEGORIES`` entry.
3. Wording: fixed, number-free category and direction lines. The text, the
   triggering statistics and a ``detection_report`` snapshot of the latest
   window (against the previous one) are frozen when the alert is queued;
   LINE shows the snapshot as a statistics image, and the read-only
   assistant can explain the saved statistics on request.

Settings, cooldown timestamps and recent alerts live in one JSON file under
``runtime_config``; the switch is independent of processing-fruit
notifications and defaults to off.
"""

from __future__ import annotations

import json
import re
import threading
import uuid
from datetime import datetime, timedelta
from pathlib import Path
from typing import Callable

from . import dataset_store, detection_report, detection_stats
from .notification import OBSERVATION_NAMES


PROCESSING = 'processing'
CATEGORY_NAMES = {**OBSERVATION_NAMES, PROCESSING: '加工果'}
DIRECTIONS = {
    'disease': '須注意病害防疫',
    'pest': '須注意蟲害防治',
    'handling': '請檢查採收與搬運作業',
    'cultivation': '請留意栽培管理與採收時機',
    'quality': '請檢視近期整體品質與田間狀況',
}
DEFAULT_CATEGORIES = {
    'bad_color': {'threshold': 0.4, 'rise': 0.15, 'direction': 'cultivation'},
    'wrinkle': {'threshold': 0.4, 'rise': 0.15, 'direction': 'cultivation'},
    'abrasion': {'threshold': 0.3, 'rise': 0.1, 'direction': 'handling'},
    'anthracnose': {'threshold': 0.2, 'rise': 0.1, 'direction': 'disease'},
    'insect_bite': {'threshold': 0.3, 'rise': 0.1, 'direction': 'pest'},
    'insect_track': {'threshold': 0.3, 'rise': 0.1, 'direction': 'pest'},
    PROCESSING: {'threshold': 0.4, 'rise': 0.15, 'direction': 'quality'},
}
DEFAULT_SETTINGS = {
    'enabled': False,
    'window_days': 7,
    'min_samples': 20,
    'cooldown_hours': 24,
    'spike_factor': 2.0,
}
STATE_VERSION = 3
# (type, minimum, maximum) for every numeric setting.
SETTING_LIMITS = {
    'window_days': (int, 1, 60),
    'cooldown_hours': (float, 0.0, 720.0),
    'min_samples': (int, 1, 10_000),
    'spike_factor': (float, 1.1, 20.0),
    'threshold': (float, 0.01, 1.0),
    'rise': (float, 0.01, 1.0),
}
REASON_TEXT = {'threshold': '比例達門檻', 'rise': '比前期上升', 'spike': '今日明顯偏高'}
DIGITS = re.compile(r'[0-9０-９%％]')
RECENT_LIMIT = 20
TITLE_LABEL_LIMIT = 12

_LOCK = threading.RLock()


def category_shares(summary: dict) -> dict:
    """Count and graded denominator per category from a ``summarize`` output."""
    graded = summary['totals']['graded']
    shares = {item['key']: {'count': item['count'], 'graded': graded, 'ratio': item['ratio']}
              for item in summary['defects']}
    processing = next(item for item in summary['grades'] if item['label'] == '加工')
    shares[PROCESSING] = {'count': processing['count'], 'graded': graded,
                          'ratio': processing['ratio']}
    return shares


def evaluate(windows: dict, settings: dict) -> list[dict]:
    """Apply the generic rules to every category; return the triggered ones.

    ``windows`` maps ``current``, ``previous``, ``today`` and ``history`` (the
    window before today) to ``category_shares`` outputs. Each comparison needs
    both sides to reach the global ``min_samples``, so a thin baseline never
    triggers.
    """
    current, previous = windows['current'], windows['previous']
    today, history = windows['today'], windows['history']
    minimum = settings['min_samples']
    triggers = []
    for key, params in settings['categories'].items():
        now, before = current[key], previous[key]
        enough = now['graded'] >= minimum
        baseline = before['graded'] >= minimum
        reasons = []
        if enough and now['count'] and now['ratio'] >= params['threshold']:
            reasons.append('threshold')
        if enough and baseline and now['count'] and now['ratio'] - before['ratio'] >= params['rise']:
            reasons.append('rise')
        day, past = today[key], history[key]
        if (day['graded'] >= minimum and past['graded'] >= minimum
                and day['count'] and day['ratio'] - past['ratio'] >= params['rise']
                and day['ratio'] >= past['ratio'] * settings['spike_factor']):
            reasons.append('spike')
        if reasons:
            triggers.append({
                'key': key, 'label': CATEGORY_NAMES[key], 'reasons': reasons,
                'direction': params['direction'],
                **{name: dict(windows[name][key]) for name in windows},
            })
    return triggers


def render_text(triggers: list[dict], *, test: bool = False) -> str:
    """One number-free message, in category order, with advice grouped by direction.

    A test message keeps the same lines after a ``測試`` heading; with no
    triggered category it only says so.
    """
    recent, spikes = [], []
    by_direction: dict[str, list[str]] = {}
    for trigger in triggers:
        labels = spikes if trigger['reasons'] == ['spike'] else recent
        labels.append(trigger['label'])
        by_direction.setdefault(trigger['direction'], []).append(trigger['label'])
    lines = ['測試 |趨勢提醒|' if test else '|趨勢提醒|']
    if not triggers:
        return '\n'.join(lines + ['目前沒有類別達到提醒條件', '（測試訊息，用來確認 LINE 與統計圖）'])
    if recent:
        lines.append(f"近來偏高：{'、'.join(recent)}")
    if spikes:
        lines.append(f"今日明顯偏高：{'、'.join(spikes)}")
    lines.append('須注意：')
    lines += [f"・{'、'.join(labels)}：{DIRECTIONS[direction]}"
              for direction, labels in by_direction.items()]
    lines += ['（模型觀察結果，僅供參考）', '數據詳情可詢問奶蛋博士獲得更多資訊']
    return '\n'.join(lines)


class TrendAlerts:
    def __init__(self, state_path: Path, detection_root: Path, outbox, *,
                 now: Callable[[], datetime] = datetime.now):
        self.state_path = Path(state_path)
        self.detection_root = Path(detection_root)
        self.outbox = outbox
        self._now = now

    def update_settings(self, changes: dict) -> dict:
        """Validate and persist Dashboard changes; invalid values raise."""
        if not isinstance(changes, dict) or not changes:
            raise ValueError('趨勢提醒設定必須是非空物件。')
        unknown = set(changes) - set(DEFAULT_SETTINGS) - {'categories'}
        if unknown:
            raise ValueError(f"未知的趨勢提醒設定：{'、'.join(sorted(unknown))}")
        with _LOCK:
            state = self._read()
            settings = _validated_settings({
                **state['settings'], **{k: v for k, v in changes.items() if k != 'categories'},
                'categories': _merged_categories(state['settings']['categories'],
                                                 changes.get('categories', {})),
            })
            state['settings'] = settings
            self._write(state)
            return settings

    def check(self) -> dict:
        """Evaluate once, save a fixed message and its statistics, then queue it."""
        with _LOCK:
            state = self._read()
            settings = state['settings']
            if not settings['enabled']:
                return {'ok': True, 'alerts': [], 'reason': 'trend_alerts_disabled', 'errors': []}
            now = self._now()
            cooldown = timedelta(hours=settings['cooldown_hours'])
            triggers = [
                trigger for trigger in evaluate(self._windows(now, settings), settings)
                if not _cooling(state['last_alerted'].get(trigger['key']), now, cooldown)
            ]
            # Reserve the cooldown first so a parallel check cannot repeat it.
            for trigger in triggers:
                state['last_alerted'][trigger['key']] = now.isoformat(timespec='seconds')
            if triggers:
                self._write(state)
        if not triggers:
            return {'ok': True, 'alerts': [], 'reason': None, 'errors': []}
        # Everything triggered by one check goes out as one message.
        alert = self._compose(triggers, settings, now)
        with _LOCK:
            state = self._read()
            state['recent'] = ([alert] + state['recent'])[:RECENT_LIMIT]
            self._write(state)
        errors = []
        try:
            self.outbox.enqueue_alert(alert['id'], alert['text'],
                                      report=self._report(alert, settings, now))
        except (OSError, ValueError) as error:
            errors.append(f"{alert['label']}：{error}")
        return {'ok': not errors, 'alerts': [alert],
                'reason': 'line_queue_failed' if errors else None, 'errors': errors}

    def send_test(self) -> dict:
        """Queue one test alert from the current data, ignoring switch and cooldown.

        Nothing is saved to the recent list or the cooldown timestamps, so a
        test never delays or replaces a real alert.
        """
        with _LOCK:
            settings = self._read()['settings']
        now = self._now()
        triggers = evaluate(self._windows(now, settings), settings)
        labels = [trigger['label'] for trigger in triggers]
        alert = {'id': f'trend_test_{uuid.uuid4().hex}',
                 'keys': [trigger['key'] for trigger in triggers], 'label': '、'.join(labels)}
        title = f"測試 趨勢提醒：{_title_label(alert['label'])}偏高" if triggers else '測試 趨勢提醒'
        queued = self.outbox.enqueue_alert(
            alert['id'], render_text(triggers, test=True),
            report=self._report(alert, settings, now, title=title))
        return {'ok': True, 'queued': queued['queued'], 'labels': labels}

    def status(self, *, include_details: bool = False) -> dict:
        """Dashboard view: settings, cooldowns, recent alerts and their LINE delivery."""
        with _LOCK:
            state = self._read()
        delivery = self.outbox.entry_statuses(alert['id'] for alert in state['recent'])
        now = self._now()
        cooldown = timedelta(hours=state['settings']['cooldown_hours'])
        return {
            'settings': state['settings'],
            # Categories still inside their cooldown, with when they may alert again.
            'cooling': {
                key: (datetime.fromisoformat(last) + cooldown).isoformat(timespec='seconds')
                for key, last in state['last_alerted'].items() if _cooling(last, now, cooldown)
            },
            'labels': dict(CATEGORY_NAMES),
            'directions': dict(DIRECTIONS),
            'line': self.outbox.configuration(),
            'recent': [
                # The message itself goes to LINE; the Dashboard lists categories only.
                {key: alert.get(key) for key in ('id', 'label', 'created_at')}
                | ({'window_days': alert.get('window_days'), 'details': alert.get('details')}
                   if include_details else {})
                | {'delivery': delivery.get(alert['id'])}
                for alert in state['recent']
            ],
        }

    def _compose(self, triggers, settings, now):
        labels = [trigger['label'] for trigger in triggers]
        return {
            'id': f'trend_{uuid.uuid4().hex}', 'keys': [trigger['key'] for trigger in triggers],
            'labels': labels, 'label': '、'.join(labels),
            'created_at': now.isoformat(timespec='seconds'),
            'window_days': settings['window_days'],
            'details': [{**trigger, **settings['categories'][trigger['key']],
                         'min_samples': settings['min_samples'],
                         'spike_factor': settings['spike_factor']}
                        for trigger in triggers],
            'text': render_text(triggers),
        }

    def _report(self, alert, settings, now, *, title=None):
        days = settings['window_days']
        window = timedelta(days=days)
        return detection_report.snapshot(
            self._records(now - window, None), previous=self._records(now - 2 * window, now - window),
            highlight=alert['keys'], now=now,
            title=title or f"趨勢提醒：{_title_label(alert['label'])}偏高",
            subtitle=f'統計區間：近 {days} 天（黑線為再前 {days} 天）',
        )

    def _windows(self, now, settings):
        window = timedelta(days=settings['window_days'])
        midnight = datetime.combine(now.date(), datetime.min.time())
        return {
            'current': self._shares(now - window, None),
            'previous': self._shares(now - 2 * window, now - window),
            'today': self._shares(midnight, None),
            'history': self._shares(midnight - window, midnight),
        }

    def _shares(self, start, end):
        return category_shares(detection_stats.summarize(self._records(start, end)))

    def _records(self, start, end):
        return detection_stats.load_records(self.detection_root, start=start, end=end)['records']

    def _read(self):
        try:
            state = json.loads(self.state_path.read_text(encoding='utf-8'))
        except FileNotFoundError:
            return {'version': STATE_VERSION, 'settings': _validated_settings({}),
                    'last_alerted': {}, 'recent': []}
        if isinstance(state, dict) and state.get('version') == 2:
            state = _migrated_from_v2(state)
        if (not isinstance(state, dict) or state.get('version') != STATE_VERSION
                or not isinstance(state.get('settings'), dict)
                or not isinstance(state.get('last_alerted'), dict)
                or not isinstance(state.get('recent'), list)):
            raise ValueError(f'趨勢提醒設定檔格式不正確：{self.state_path}')
        stored = state['settings']
        state['settings'] = _validated_settings({
            **stored, 'categories': _merged_categories(DEFAULT_CATEGORIES, stored.get('categories', {})),
        })
        return state

    def _write(self, state):
        self.state_path.parent.mkdir(parents=True, exist_ok=True)
        dataset_store.atomic_write_json(self.state_path, state)


def _merged_categories(base, changes):
    if not isinstance(changes, dict):
        raise ValueError('categories 必須是物件。')
    unknown = set(changes) - set(DEFAULT_CATEGORIES)
    if unknown:
        raise ValueError(f"未知的提醒類別：{'、'.join(sorted(unknown))}")
    merged = {key: dict(DEFAULT_CATEGORIES[key], **base.get(key, {})) for key in DEFAULT_CATEGORIES}
    for key, params in changes.items():
        if not isinstance(params, dict) or set(params) - set(DEFAULT_CATEGORIES[key]):
            raise ValueError(f'{key} 只能設定 threshold、rise、direction。')
        merged[key].update(params)
    return merged


def _validated_settings(settings):
    result = {}
    for key, default in DEFAULT_SETTINGS.items():
        value = settings.get(key, default)
        if key == 'enabled':
            if type(value) is not bool:
                raise ValueError('趨勢提醒開關必須是 true 或 false。')
            result[key] = value
        else:
            result[key] = _number(key, value)
    result['categories'] = {}
    for key, params in settings.get('categories', DEFAULT_CATEGORIES).items():
        if params.get('direction') not in DIRECTIONS:
            raise ValueError(f'{key}.direction 必須是 {"、".join(DIRECTIONS)} 之一。')
        result['categories'][key] = {
            **{name: _number(name, params[name], label=f'{key}.{name}')
               for name in ('threshold', 'rise')},
            'direction': params['direction'],
        }
    return result


def _number(name, value, *, label=None):
    kind, low, high = SETTING_LIMITS[name]
    label = label or name
    if type(value) is bool or not isinstance(value, (int, float)):
        raise ValueError(f'{label} 必須是數字。')
    if kind is int and value != int(value):
        raise ValueError(f'{label} 必須是整數。')
    if not low <= value <= high:
        raise ValueError(f'{label} 必須介於 {low} 與 {high} 之間。')
    return kind(value)


def _title_label(label):
    # Long category lists overflow the image title; the chart marks them in red anyway.
    return label if len(label) <= TITLE_LABEL_LIMIT else '多項指標'


def _migrated_from_v2(state):
    """v2 kept a minimum per category plus one for today; keep the loosest one."""
    settings = dict(state.get('settings') or {})
    categories = settings.get('categories') or {}
    minimums = [params['min_samples'] for params in categories.values()
                if isinstance(params, dict) and 'min_samples' in params]
    if 'spike_min_samples' in settings:
        minimums.append(settings.pop('spike_min_samples'))
    settings['min_samples'] = min(minimums, default=DEFAULT_SETTINGS['min_samples'])
    settings['categories'] = {
        key: {name: value for name, value in params.items() if name != 'min_samples'}
        for key, params in categories.items() if isinstance(params, dict)
    }
    return {**state, 'version': STATE_VERSION, 'settings': settings}


def _cooling(last, now, cooldown):
    return bool(last) and now - datetime.fromisoformat(last) < cooldown
